-- Tabelas do diagrama de classes (docs/uml/v2). SQL comum a PostgreSQL e H2.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL
);

CREATE TABLE cliente (
    id BIGINT PRIMARY KEY REFERENCES usuario (id),
    rg VARCHAR(20) NOT NULL UNIQUE,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    profissao VARCHAR(80) NOT NULL,
    logradouro VARCHAR(120) NOT NULL,
    numero VARCHAR(10) NOT NULL,
    complemento VARCHAR(60),
    bairro VARCHAR(60) NOT NULL,
    cidade VARCHAR(60) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL
);

CREATE TABLE rendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente (id),
    entidade_empregadora VARCHAR(120) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0)
);

CREATE TABLE agente (
    id BIGINT PRIMARY KEY REFERENCES usuario (id),
    nome VARCHAR(120) NOT NULL,
    cnpj VARCHAR(18) NOT NULL UNIQUE
);

CREATE TABLE empresa (
    id BIGINT PRIMARY KEY REFERENCES agente (id)
);

CREATE TABLE banco (
    id BIGINT PRIMARY KEY REFERENCES agente (id)
);

CREATE TABLE automovel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL UNIQUE,
    ano INTEGER NOT NULL,
    marca VARCHAR(40) NOT NULL,
    modelo VARCHAR(60) NOT NULL,
    placa VARCHAR(7) NOT NULL UNIQUE,
    valor_diaria NUMERIC(10, 2) NOT NULL CHECK (valor_diaria > 0),
    proprietario_id BIGINT NOT NULL REFERENCES usuario (id)
);

CREATE TABLE parecer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    positivo BOOLEAN NOT NULL,
    justificativa VARCHAR(1000) NOT NULL,
    data TIMESTAMP NOT NULL,
    agente_id BIGINT NOT NULL REFERENCES agente (id)
);

CREATE TABLE pedido_aluguel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente (id),
    automovel_id BIGINT NOT NULL REFERENCES automovel (id),
    data_criacao TIMESTAMP NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    parecer_id BIGINT UNIQUE REFERENCES parecer (id),
    CHECK (data_fim >= data_inicio),
    CHECK (status IN ('ENVIADO', 'EM_ANALISE', 'APROVADO', 'REPROVADO', 'CONTRATADO', 'CANCELADO'))
);

CREATE TABLE contrato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(30) NOT NULL,
    data_assinatura DATE NOT NULL,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedido_aluguel (id),
    agente_id BIGINT NOT NULL REFERENCES agente (id),
    CHECK (tipo IN ('PROPRIEDADE_CLIENTE', 'PROPRIEDADE_EMPRESA', 'PROPRIEDADE_BANCO'))
);

CREATE TABLE contrato_credito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    taxa_juros NUMERIC(5, 2) NOT NULL CHECK (taxa_juros >= 0),
    parcelas INTEGER NOT NULL CHECK (parcelas > 0),
    contrato_id BIGINT NOT NULL UNIQUE REFERENCES contrato (id),
    banco_id BIGINT NOT NULL REFERENCES banco (id)
);

CREATE INDEX idx_rendimento_cliente ON rendimento (cliente_id);
CREATE INDEX idx_pedido_cliente ON pedido_aluguel (cliente_id);
CREATE INDEX idx_pedido_status ON pedido_aluguel (status);
CREATE INDEX idx_automovel_proprietario ON automovel (proprietario_id);
